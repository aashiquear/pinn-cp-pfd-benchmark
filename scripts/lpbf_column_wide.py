#!/usr/bin/env python3
"""Part V: write the standalone decks of the WIDE build column with melt-pool flow.

usage: scripts/lpbf_column_wide.py <element size in um> [<element size> ...]

Reads decks/lpbf/in718/k2/k2_column_flow_h10.i (the 600 um column of report section
6.11) and writes decks/lpbf/in718/k2/k2_column_flow_wide_h<size>.i: the same build (four
layers of 40 um, five tracks of 440 um per layer, 285 W, 960 mm/s, hatch 110 um, 90
degrees between layers) in a block of 1.2 x 1.2 mm, so that the pool with flow stays
380 um away from the sides. What changes against the source deck:

  block        1200 x 1200 x 360 um; scan centre 600, 600; 4,000 plate grains (the same
               grain size as 1,000 in the small block)
  mesh         the given element size; the lengths tied to it follow: band thicknesses
               and mesh_size = h, grain-boundary width 4 h, width of the initial grain
               boundaries 2 h, seed radius 1.5 h; step 0.5 us x (h / 10 um)^2
  dwell        at least 1.0 ms between tracks and 3.0 ms between layers; the scan is
               HELD at the start of every track and layer until no element is liquid
               (`hold_scan_until_solid`), and the next layer is spread at the END of the
               layer dwell (`recoat = dwell_end`): every pool freezes by itself before
               the next track or layer starts. The run ends when the path is over and
               all is solid (`stop_when_solid`); `end_time` is an upper limit. Check with
               `scripts/lpbf_column.py <deck> dwell` after the run.
  records      frames every 200 us (reduced on each rank to the grain map, the solid
               share, the temperature and the velocity), series every 200 us

The decks are meant for several GPUs: run with
  scripts/lpbf_column.py <deck> run global.rank_devices="cuda:0 cuda:2 cuda:5"
(PINNACLE ADR 0057; `scripts/gpu_free.py` lists the free cards). Without `rank_devices`
a deck runs on one device.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "decks" / "lpbf" / "in718" / "k2" / "k2_column_flow_h10.i"
MEMORY_PER_ELEMENT = 36.3e3  # bytes on the device, measured 2026-11-26 (float64, 30 grains)


def label(size: float) -> str:
    return f"{size:g}".replace(".", "p")


def write(size_um: float) -> Path:
    h = size_um * 1.0e-6
    divisions = [round(1200.0 / size_um), round(1200.0 / size_um), round(360.0 / size_um)]
    for count, length in zip(divisions, (1200.0, 1200.0, 360.0), strict=True):
        if abs(count * size_um - length) > 1e-9 or abs(40.0 / size_um - round(40.0 / size_um)) > 1e-9:
            raise SystemExit(f"{size_um} um does not divide the block (1200, 360) and the layer (40).")
    elements = divisions[0] * divisions[1] * divisions[2]
    dt = 5.0e-7 * (size_um / 10.0) ** 2
    scan_time = 4 * (5 * 440.0e-6 / 0.96 + 4 * 1.0e-3) + 3 * 3.0e-3
    planned = scan_time + 3.0e-3
    end_time = planned + 2.0e-2  # upper limit: room for the holds
    name = f"column_flow_wide_h{label(size_um)}"
    text = SOURCE.read_text()

    def swap(old: str, new: str, count: int = 1) -> None:
        nonlocal text
        if text.count(old) != count:
            raise SystemExit(f"source deck changed: {old!r} found {text.count(old)} times, expected {count}")
        text = text.replace(old, new)

    head = text.index("[Global]")
    gb = elements * MEMORY_PER_ELEMENT / 2**30
    header = f"""# GENERATED by scripts/lpbf_column_wide.py from k2_column_flow_h10.i: element size {size_um:g} um.
# Part V, case K2 WITH MELT-POOL FLOW in a WIDE block, for several GPUs.
#
# PROBLEM: the build column of k2_column_flow_h10.i (four powder layers of 40 um on 200 um
#   of plate, five tracks of 440 um per layer, 285 W, 960 mm/s, hatch 110 um, 90 degrees
#   between layers; temperature, velocity and pressure of the liquid, 30 grain fields) in
#   a block of 1.2 x 1.2 mm. In the 600 um block the pool with flow reached the walls
#   and the whole block became one pool (report section 6.11); here the scanned patch
#   keeps 380 um to every side. 4,000 plate grains (the grain size of the small block).
#
# DWELL: at least 1.0 ms between two tracks and 3.0 ms between two layers, and the scan
#   is HELD at the start of every track and of every layer until no element is liquid
#   (`hold_scan_until_solid` of the process state): a dwell is as long as the freezing
#   needs. (A single track with flow on the plate is solid 0.3 to 0.7 ms after the beam
#   has left; in a conduction check with a fixed 1 ms the third track of a layer still
#   started on liquid.) The next layer is spread when the layer dwell ENDS
#   (`recoat = dwell_end`), so the pool of a layer freezes under its own surface; only
#   then the block is set to the plate temperature (`layer_reset_temperature`, standing
#   for the tens of seconds of recoating). The history carries the accumulated hold
#   (`state.scan_delay`). After the run, `scripts/lpbf_column.py <this deck> dwell` lists
#   the liquid elements at the start of every track and layer: all must be 0.
#
# MESH AND MEMORY: {divisions[0]} x {divisions[1]} x {divisions[2]} = {elements:,} elements of {size_um:g} um. On the device
#   about 36 kB per element (measured: 4.70 GB for 129,600 elements, float64), so
#   {gb:.0f} GB in all: {gb / 2:.0f} GB per card on two cards, {gb / 3:.0f} on three, {gb / 4:.0f} on four.
#
# TIME: explicit steps of {dt * 1e6:.4g} us; {round(planned / dt):,} steps to {planned * 1e3:.1f} ms if no hold is
#   needed, more by the holds. The run ends when the path is over and all is solid
#   (`stop_when_solid`); `end_time` ({end_time * 1e3:.1f} ms) is an upper limit. Velocity and pressure
#   take four sub-steps per step (sound speed 25 m/s).
#
# SEVERAL GPUS (PINNACLE ADR 0057): name the cards at run time,
#     scripts/lpbf_column.py <this deck> run global.rank_devices="cuda:0 cuda:2 cuda:5"
#   The mesh is cut into one slab per card; the result does not depend on the cut.
#   `scripts/gpu_free.py <GB per card>` prints the cards with that much free memory.
#
# PARAMETERS: as k2_column_flow_h10.i (flow constants of the single-track study, grain
#   parameters of k2_column_h10.i); nothing is fitted here. The lengths tied to the
#   element follow it: band thicknesses and mesh_size {size_um:g} um, grain-boundary width
#   {4 * size_um:g} um, initial boundary width {2 * size_um:g} um, seed radius {1.5 * size_um:g} um.
#
# UNITS: SI (m, s, K, W, J, Pa).

"""
    text = text[head:]
    swap("column_flow_h10", name, 4)
    swap("domain    = '0.0 0.0 0.0 600.0e-6 600.0e-6 360.0e-6'", "domain    = '0.0 0.0 0.0 1200.0e-6 1200.0e-6 360.0e-6'")
    swap("divisions = '60 60 36'", f"divisions = '{divisions[0]} {divisions[1]} {divisions[2]}'")
    swap("center            = '300.0e-6 300.0e-6 240.0e-6'", "center            = '600.0e-6 600.0e-6 240.0e-6'")
    swap("    track_dwell       = 2.0e-4\n    layer_dwell       = 2.5e-3\n",
         "    track_dwell       = 1.0e-3       # a track is solid before the next starts\n"
         "    layer_dwell       = 3.0e-3       # a layer is solid before the next is spread\n"
         "    recoat            = dwell_end\n")
    swap("    series_interval         = 1.0e-4\n",
         "    series_interval         = 2.0e-4\n"
         "    hold_scan_until_solid   = true         # a track starts on solid material only\n"
         "    stop_when_solid         = true         # end of the run: path over, all solid\n")
    swap("    record_every            = 2000         # the record file is refreshed every 1 ms: a sign of life\n", "")
    swap("    seed_radius         = 15.0e-6\n", f"    seed_radius         = {1.5 * h:.4e}\n")
    swap("    band_thickness           = 10.0e-6\n", f"    band_thickness           = {h:.4e}\n", 2)
    swap("    band_thickness  = 10.0e-6\n", f"    band_thickness  = {h:.4e}\n")
    swap("    mesh_size     = 10.0e-6\n", f"    mesh_size     = {h:.4e}\n")
    swap("    mesh_size             = 10.0e-6\n", f"    mesh_size             = {h:.4e}\n")
    swap("    boundary_width      = 40.0e-6\n", f"    boundary_width      = {4 * h:.4e}\n")
    swap("    n_grains       = 1000\n", "    n_grains       = 4000\n")
    swap("    int_width      = 20.0e-6\n", f"    int_width      = {2 * h:.4e}\n")
    swap("  dt              = 5.0e-7\n", f"  dt              = {dt:.6e}\n")
    swap("  end_time        = 2.26e-2          # four layers: 4 x 3.09 ms scanning + 3 x 2.5 ms dwell + 2.7 ms to freeze\n",
         f"  end_time        = {end_time:.6e}     # upper limit; planned {planned * 1e3:.1f} ms plus the holds\n")
    swap("  snapshots_every = 200             # 100 us\n", f"  snapshots_every = {round(2.0e-4 / dt)}             # 200 us\n")
    target = SOURCE.with_name(f"k2_{name}.i")
    target.write_text(header + text)
    print(f"{target.relative_to(REPO)}: {elements:,} elements, {gb:.0f} GB on the devices, "
          f"{round(planned / dt):,} steps of {dt * 1e6:.4g} us without holds")
    return target


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    for value in sys.argv[1:]:
        write(float(value))
