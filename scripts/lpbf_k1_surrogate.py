#!/usr/bin/env python3
"""Part V, network route on case K1: training data of the single-track surrogate.

usage: scripts/lpbf_k1_surrogate.py <design deck> design | decks | run | targets

  design   Latin hypercube design over laser power, scan speed and beam diameter
           (<out_dir>/design.csv)
  decks    one standalone PINNACLE deck per design row from the K1 template
  run      run them one after another (skips finished ones)
  targets  what PINNACLE's `parametric_surrogate` reads with `samples_file` / `data_dir`:
           <out_dir>/targets/<i:04d>/target.npz with `t` (depth below the surface on the
           track axis, um), `y` (peak temperature reached there, K), `s` (melt-pool depth
           and width, um, mean of the solidus and liquidus isotherms), and
           <out_dir>/targets/samples.csv (power, speed, d4sigma per sample); also
           <out_dir>/targets/nist_cases.csv, the seven NIST cases as query rows.

The cross-section reduction is `lpbf_k1.cross_section`; nothing here runs a network.
"""

from __future__ import annotations

import csv
import os
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lpbf_k1  # noqa: E402


def read_deck(path: Path) -> dict:
    sys.path.insert(0, lpbf_k1.PINNACLE_SRC)
    from pinnacle.io.i_parser import InputParser
    from pinnacle.io.translator import Translator

    cfg = Translator().translate(InputParser().parse(path.read_text()))
    if "design" not in cfg:
        raise SystemExit(f"{path}: missing [Design] block")
    return cfg["design"]


def pair(value) -> tuple[float, float]:
    items = value if isinstance(value, (list, tuple)) else str(value).split()
    return float(items[0]), float(items[1])


def design_rows(deck: Path, cfg: dict) -> list[dict]:
    path = lpbf_k1.resolve(cfg["out_dir"], deck) / "design.csv"
    with path.open() as fh:
        return [{k: float(v) if k != "sample" else int(v) for k, v in row.items()}
                for row in csv.DictReader(fh)]


def cmd_design(deck: Path, cfg: dict) -> None:
    n = int(cfg["samples"])
    rng = np.random.default_rng(int(cfg["seed"]))
    names = ("power_W", "speed_mm_s", "d4sigma_um")
    columns = []
    for name in names:
        lo, hi = pair(cfg[name])
        strata = (rng.permutation(n) + rng.random(n)) / n
        columns.append(lo + strata * (hi - lo))
    out = lpbf_k1.resolve(cfg["out_dir"], deck)
    out.mkdir(parents=True, exist_ok=True)
    with (out / "design.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["sample", *names])
        for i in range(n):
            w.writerow([i, *(f"{c[i]:.4f}" for c in columns)])
    print("wrote", out / "design.csv", f"({n} samples)")


def cmd_decks(deck: Path, cfg: dict) -> None:
    template = lpbf_k1.resolve(cfg["template"], deck).read_text()
    h = float(cfg["mesh_um"]) * 1e-6
    n = [int(round(d * 1e-6 / h)) for d in lpbf_k1.DOMAIN_UM]
    dt = 0.8 * h * h / (6.0 * lpbf_k1.DIFFUSIVITY)
    k_liquid = " ".join(f"{t:.2f} {k:.3f}" for t, k in lpbf_k1.K_LIQUID)
    case_dir = lpbf_k1.resolve(cfg["case_dir"], deck)
    case_dir.mkdir(parents=True, exist_ok=True)
    out = lpbf_k1.resolve(cfg["out_dir"], deck)
    for row in design_rows(deck, cfg):
        name = f"s{row['sample']:02d}"
        run_dir = out / "runs" / name
        fields = {
            "BACKEND": str(cfg["backend"]), "USE_GPU": "true" if cfg["use_gpu"] else "false",
            "OUT_DIR": os.path.relpath(run_dir, case_dir), "NX": n[0], "NY": n[1], "NZ": n[2],
            "POWER": f"{row['power_W']:.2f}", "SPEED": f"{row['speed_mm_s'] * 1e-3:.5f}",
            "RADIUS": f"{0.5 * row['d4sigma_um'] * 1e-6:.4e}",
            "ABSORPTIVITY": f"{float(cfg['absorptivity']):.5f}",
            "PENETRATION": f"{float(cfg['penetration_um']) * 1e-6:.5e}",
            "BAND": f"{h:.3e}", "DT": f"{dt:.4e}", "END_TIME": f"{float(cfg['end_time']):.4e}",
            "K_LIQUID": k_liquid,
        }
        text = template
        for key, value in fields.items():
            text = text.replace("{" + key + "}", str(value))
        if re.findall(r"\{[A-Z_]+\}", text.split("[Global]", 1)[1]):
            raise SystemExit("template fields not filled")
        (case_dir / f"{name}.i").write_text(
            f"# GENERATED by scripts/lpbf_k1_surrogate.py from {deck.name}: design sample "
            f"{row['sample']} (P {row['power_W']:.1f} W, v {row['speed_mm_s']:.0f} mm/s, "
            f"D4sigma {row['d4sigma_um']:.1f} um).\n" + text)
    print("wrote", len(design_rows(deck, cfg)), "decks to", case_dir)


def cmd_run(deck: Path, cfg: dict) -> None:
    case_dir = lpbf_k1.resolve(cfg["case_dir"], deck)
    out = lpbf_k1.resolve(cfg["out_dir"], deck)
    for row in design_rows(deck, cfg):
        name = f"s{row['sample']:02d}"
        run_dir = out / "runs" / name
        if (run_dir / "process_state.npz").is_file() and (run_dir / "wall.json").is_file():
            continue
        wall = lpbf_k1.run_case(case_dir / f"{name}.i", run_dir)
        print(f"{name}: {wall:.0f} s", flush=True)


def profile(record: Path, points: int, depth_um: float) -> tuple[np.ndarray, np.ndarray]:
    """Peak temperature along the depth below the track axis, at mid-length."""
    d = np.load(record)
    c, peak = d["centroid"], d["peak_temperature"]
    xs, ys, zs = (np.unique(np.round(c[:, i], 12)) for i in range(3))
    order = np.lexsort((c[:, 0], c[:, 1], c[:, 2]))
    grid = peak[order].reshape(zs.size, ys.size, xs.size)
    jc, ic = ys.size // 2, xs.size // 2
    column = 0.5 * (grid[:, jc - 1, ic - 2 : ic + 2].mean(axis=1) + grid[:, jc, ic - 2 : ic + 2].mean(axis=1))
    top = zs[-1] + 0.5 * (zs[1] - zs[0])
    depth = (top - zs)[::-1] * 1e6  # increasing
    values = column[::-1]
    wanted = np.linspace(depth[0], depth_um, points)
    return wanted, np.interp(wanted, depth, values)


def cmd_targets(deck: Path, cfg: dict) -> None:
    out = lpbf_k1.resolve(cfg["out_dir"], deck)
    target_dir = out / "targets"
    target_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for row in design_rows(deck, cfg):
        name = f"s{row['sample']:02d}"
        record = out / "runs" / name / "process_state.npz"
        if not record.is_file():
            print("missing", name)
            continue
        depth_l, width_l, _ = lpbf_k1.cross_section(record, lpbf_k1.LIQUIDUS)
        depth_s, width_s, _ = lpbf_k1.cross_section(record, lpbf_k1.SOLIDUS)
        t, y = profile(record, int(cfg["profile_points"]), float(cfg["profile_depth_um"]))
        folder = target_dir / f"{row['sample']:04d}"
        folder.mkdir(exist_ok=True)
        s = np.array([0.5e6 * (depth_l + depth_s), 0.5e6 * (width_l + width_s)])
        np.savez(folder / "target.npz", t=t, y=y[:, None], s=s)
        rows.append([row["sample"], row["power_W"], row["speed_mm_s"], row["d4sigma_um"], s[0], s[1]])
    with (target_dir / "samples.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["sample", "power", "speed", "d4sigma", "depth_um", "width_um"])
        w.writerows(rows)
    nist = lpbf_k1.resolve(cfg["nist_targets"], deck)
    with nist.open() as fh:
        table = [r for r in csv.reader(fh) if r and not r[0].startswith("#")]
    with (target_dir / "nist_cases.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["power", "speed", "d4sigma"])
        for r in table[1:]:
            w.writerow([r[1], r[2], r[3]])
    print(f"wrote {len(rows)} targets and samples.csv, nist_cases.csv to {target_dir}")


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    deck = Path(sys.argv[1]).resolve()
    cfg = read_deck(deck)
    {"design": cmd_design, "decks": cmd_decks, "run": cmd_run, "targets": cmd_targets}.get(
        sys.argv[2], lambda *_: (_ for _ in ()).throw(SystemExit(__doc__)))(deck, cfg)


if __name__ == "__main__":
    main()
